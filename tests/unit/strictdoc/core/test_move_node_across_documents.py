# Regression test: moving a node whose type belongs to a custom grammar
# element (e.g. "FEATURE", as used by StrictDoc's own docs) into a document
# whose grammar does not define that element type used to crash rendering
# with a KeyError in get_requirement_style_mode() instead of being rejected
# up front.
def test_move_node_with_incompatible_grammar_type_raises_validation_error():
    traceability_index, document_1, doc1_reqs, document_2, doc2_reqs = (
        _build_two_document_index()
    )
    moved_requirement = doc1_reqs[0]
    moved_requirement.node_type = "FEATURE"
    assert document_1.grammar is not None
    document_1.grammar.elements_by_type["FEATURE"] = (
        GrammarElement.create_default("FEATURE")
    )
    # document_2's grammar (default) does not define "FEATURE".

    target_requirement = doc2_reqs[0]

    assert not traceability_index.is_move_grammar_compatible(
        moved_requirement, document_2
    )

    command = MoveNodeAcrossDocumentsCommand(
        moved_node=moved_requirement,
        target_node=target_requirement,
        whereto=NodeCreationOrder.AFTER,
        traceability_index=traceability_index,
    )
    with pytest.raises(SingleValidationError):
        command.perform()

    # The rejected move must not have mutated the tree.
    assert moved_requirement in document_1.section_contents
    assert moved_requirement not in document_2.section_contents


