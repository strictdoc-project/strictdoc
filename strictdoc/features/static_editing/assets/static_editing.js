// static_editing.js
//
// The static editor of the STATIC_EDITING feature. It runs on the DOCUMENT
// screen of a static HTML export, where no StrictDoc server is available.
//
// - The export writes the static editing data of the document into
//   <document>.edit.js. The script reads it from
//   window.StrictDocStaticEditingData.
// - The edit button of a node opens a form with the source values of the
//   node fields. The form reuses the markup and styles of the server forms.
// - Saving the form stores a change in the IndexedDB of the browser. The
//   change survives a page reload.
// - The panel at the bottom of the page exports all stored changes of the
//   project as one JSON file. A StrictDoc command applies the JSON file to the
//   SDoc source files.
//
// @relation(SDOC-SRS-215, scope=file)

(() => {
  const DATA = window.StrictDocStaticEditingData;
  if (!DATA) {
    console.warn('static_editing.js: the static editing data is missing.');
    return;
  }

  const CHANGES_SCHEMA = 'strictdoc-static-editing-changes';
  const CHANGES_VERSION = 1;
  const DATABASE_VERSION = 1;
  const STORE_NAME = 'changes';

  // Fields that the static editor shows, but does not let the user edit.
  // A changed UID or MID would break the identity of the node and its
  // incoming relations.
  const READ_ONLY_FIELDS = new Set(['UID', 'MID']);

  // Fields that a node can have several times. The form offers to add an
  // instance.
  const MULTI_INSTANCE_FIELDS = new Set(['COMMENT']);

  // A comment that a user adds starts with the name or initials of the user,
  // for example "[bob] The text of the comment".
  const AUTHOR_TAGGED_FIELDS = new Set(['COMMENT']);

  const NOT_EDITABLE_MESSAGES = {
    autogenerated: 'Editing is disabled for autogenerated nodes',
    managed_by_source_code: 'Editing is disabled for nodes managed by source code',
    no_stable_identifier:
      'Editing requires a UID or a MID in the source file. See the "Static editing" section of the StrictDoc user guide.',
  };

  const nodesByHtmlMid = new Map(DATA.nodes.map((node_) => [node_.html_mid, node_]));
  const elementsByTag = new Map(DATA.grammar.elements.map((element_) => [element_.tag, element_]));

  // Changes of this document, by change key. Kept in sync with the store.
  const documentChanges = new Map();

  //
  // Change keys and the change store.
  //

  function nodeKey(node) {
    if (node.uid !== null) return `uid:${node.uid}`;
    return `mid:${node.mid}`;
  }

  function changeKey(node) {
    return `${DATA.document.path}#${nodeKey(node)}`;
  }

  function projectHash() {
    const meta = document.querySelector('meta[name="strictdoc-project-hash"]');
    return meta ? meta.content : 'default';
  }

  // The author name is a convenience of the viewer and lives in
  // localStorage. Reading or writing can fail, for example in a private
  // window, and the editor then keeps the name until the page reloads.
  const authorStorageKey = `strictdoc-static-editing-author-${projectHash()}`;
  let authorName = '';
  try {
    authorName = window.localStorage.getItem(authorStorageKey) || '';
  } catch (error) {
    authorName = '';
  }

  function setAuthorName(name) {
    authorName = name.trim();
    try {
      window.localStorage.setItem(authorStorageKey, authorName);
    } catch (error) {
      // The name stays in memory only.
    }
  }

  function tagWithAuthor(text) {
    const tag = `[${authorName}]`;
    if (text.startsWith(tag)) return text;
    return `${tag} ${text}`;
  }

  // The store of all changes of the project. A project published on a shared
  // origin, for example GitHub Pages, gets its own database name.
  const store = createStore(`strictdoc-static-editing-${projectHash()}`);

  function createStore(databaseName) {
    let databasePromise = null;

    function openDatabase() {
      if (databasePromise === null) {
        databasePromise = new Promise((resolve, reject) => {
          const request = window.indexedDB.open(databaseName, DATABASE_VERSION);
          request.onupgradeneeded = () => {
            request.result.createObjectStore(STORE_NAME, { keyPath: 'key' });
          };
          request.onsuccess = () => resolve(request.result);
          request.onerror = () => reject(request.error);
        });
      }
      return databasePromise;
    }

    function run(mode, action) {
      return openDatabase().then(
        (database) =>
          new Promise((resolve, reject) => {
            const transaction = database.transaction(STORE_NAME, mode);
            const request = action(transaction.objectStore(STORE_NAME));
            transaction.oncomplete = () => resolve(request ? request.result : undefined);
            transaction.onerror = () => reject(transaction.error);
          }),
      );
    }

    // The memory store keeps the changes until the page reloads. It is used
    // when the browser offers no IndexedDB, for example in a private window
    // of some browsers.
    const memory = new Map();
    let useMemory = !window.indexedDB;

    function withFallback(databaseAction, memoryAction) {
      if (useMemory) return Promise.resolve(memoryAction());
      return databaseAction().catch((error) => {
        console.warn('static_editing.js: IndexedDB is not available, changes are kept until the page reloads.', error);
        useMemory = true;
        return memoryAction();
      });
    }

    return {
      getAll: () =>
        withFallback(
          () => run('readonly', (objectStore) => objectStore.getAll()),
          () => Array.from(memory.values()),
        ),
      put: (change) =>
        withFallback(
          () => run('readwrite', (objectStore) => objectStore.put(change)),
          () => memory.set(change.key, change),
        ),
      delete: (key) =>
        withFallback(
          () => run('readwrite', (objectStore) => objectStore.delete(key)),
          () => memory.delete(key),
        ),
      clear: () =>
        withFallback(
          () => run('readwrite', (objectStore) => objectStore.clear()),
          () => memory.clear(),
        ),
    };
  }

  //
  // Field values.
  //

  // The source values of each field, by field name. A field can have several
  // instances, for example several COMMENT fields.
  function originalFieldInstances(node) {
    const instances = new Map();
    node.fields.forEach((field_) => {
      if (!instances.has(field_.name)) instances.set(field_.name, []);
      instances.get(field_.name).push(field_.value);
    });
    return instances;
  }

  // A field change is one of:
  // - an edited instance: { name, index, old_value, new_value }. `index` is
  //   the position among the instances of the field at export time. The old
  //   value identifies the instance and detects conflicts.
  // - an added instance: { name, index: null, old_value: null, new_value }.
  // An empty new value of an edited instance removes the instance.
  function storedFieldChanges(node) {
    const change = documentChanges.get(changeKey(node));
    return change ? change.fields : [];
  }

  //
  // The edit form.
  //

  function createElement(tagName, attributes = {}, children = []) {
    const element = document.createElement(tagName);
    Object.entries(attributes).forEach(([name_, value_]) => {
      if (value_ !== null && value_ !== undefined) element.setAttribute(name_, value_);
    });
    children.forEach((child_) => element.append(child_));
    return element;
  }

  // `index` is the instance index, or null for an added instance.
  function createFieldRow(grammarField, index, value, editable) {
    const fieldType = grammarField.multiline ? 'multiline' : 'singleline';
    const label = editable ? grammarField.title : `${grammarField.title} (READ-ONLY)`;
    const instanceName = index === null ? 'new' : String(index);
    const inputName = `static_editing_field[${grammarField.title}][${instanceName}]`;

    const editableField = createElement('sdoc-contenteditable', {
      'data-js-editable-field': '',
      role: 'textbox',
      'data-field-type': fieldType,
      contenteditable: editable ? 'true' : 'false',
      id: inputName,
      placeholder: `Enter ${grammarField.title} here...`,
      'data-field-label': grammarField.required ? `${label} *` : label,
      'data-static-editing-field': grammarField.title,
      'data-static-editing-index': instanceName,
      'data-testid': `form-field-${grammarField.title}`,
    });
    editableField.textContent = value;

    const hiddenInput = createElement('input', { type: 'hidden', name: inputName, value });

    return createElement('sdoc-form-row', { 'data-static-editing-row': grammarField.title }, [
      createElement('sdoc-form-row-aside'),
      createElement('sdoc-form-row-main', {}, [createElement('sdoc-form-field', {}, [editableField, hiddenInput])]),
      createElement('sdoc-form-row-aside'),
    ]);
  }

  function fieldText(editableField) {
    // editable_field.js keeps the hidden input next to the field in sync
    // with the field text.
    const hiddenInput = editableField.parentElement.querySelector('input[type="hidden"]');
    return hiddenInput ? hiddenInput.value : editableField.innerText;
  }

  function validateField(grammarField, value, isOnlyInstance) {
    if (grammarField.required && isOnlyInstance && value.trim().length === 0) {
      return `${grammarField.title} must not be empty. If there is no appropriate value for this field yet, enter TBD (to be done) or TBC (to be confirmed).`;
    }
    if (grammarField.options && value.trim().length > 0) {
      const values =
        grammarField.type === 'MultipleChoice'
          ? value.split(',').map((value_) => value_.trim())
          : [value.trim()];
      const invalidValues = values.filter((value_) => !grammarField.options.includes(value_));
      if (invalidValues.length > 0) {
        return `Invalid value: ${invalidValues.join(', ')}. Valid values: ${grammarField.options.join(', ')}.`;
      }
    }
    return null;
  }

  function showFieldError(editableField, message) {
    const formField = editableField.closest('sdoc-form-field');
    formField.querySelectorAll('sdoc-form-error').forEach((error_) => error_.remove());
    if (message === null) {
      editableField.removeAttribute('errors');
      return;
    }
    editableField.setAttribute('errors', 'true');
    formField.append(createElement('sdoc-form-error', {}, [message]));
  }

  // The rows of one grammar field: one row per existing instance with the
  // stored change applied, one row per added instance, and an empty row if
  // the field has no instance yet.
  function createFieldRows(grammarField, originalInstances, fieldChanges) {
    const editable = !READ_ONLY_FIELDS.has(grammarField.title);
    const rows = [];
    originalInstances.forEach((originalValue_, index_) => {
      const edited = fieldChanges.find(
        (change_) => change_.name === grammarField.title && change_.index === index_,
      );
      rows.push(createFieldRow(grammarField, index_, edited ? edited.new_value : originalValue_, editable));
    });
    const added = fieldChanges.filter((change_) => change_.name === grammarField.title && change_.index === null);
    added.forEach((change_) => rows.push(createFieldRow(grammarField, null, change_.new_value, editable)));
    if (rows.length === 0 && editable) {
      rows.push(createFieldRow(grammarField, null, '', editable));
    }
    return rows;
  }

  function openForm(nodeElement, node) {
    if (nodeElement.parentElement.querySelector('sdoc-form[data-static-editing-form]')) return;

    const element = elementsByTag.get(node.node_type);
    const instances = originalFieldInstances(node);
    const fieldChanges = storedFieldChanges(node);

    const grid = createElement('sdoc-form-grid');
    element.fields.forEach((grammarField_) => {
      const originalInstances = instances.get(grammarField_.title) || [];
      createFieldRows(grammarField_, originalInstances, fieldChanges).forEach((row_) => grid.append(row_));

      if (MULTI_INSTANCE_FIELDS.has(grammarField_.title)) {
        const addButton = createElement(
          'button',
          {
            type: 'button',
            class: 'action_button',
            'data-testid': `form-add-field-${grammarField_.title}`,
          },
          [`Add ${grammarField_.title.toLowerCase()}`],
        );
        const addRow = createElement('sdoc-form-row', {}, [
          createElement('sdoc-form-row-aside'),
          createElement('sdoc-form-row-main', {}, [addButton]),
          createElement('sdoc-form-row-aside'),
        ]);
        addButton.addEventListener('click', () => {
          const newRow = createFieldRow(grammarField_, null, '', true);
          addRow.before(newRow);
          newRow.querySelector('[contenteditable="true"]').focus();
        });
        grid.append(addRow);
      }
    });

    const saveButton = createElement(
      'button',
      {
        type: 'submit',
        class: 'action_button',
        'data-action-type': 'submit',
        'data-testid': 'form-submit-action',
      },
      ['Save'],
    );
    const cancelButton = createElement(
      'button',
      {
        type: 'button',
        class: 'action_button',
        'data-action-type': 'cancel',
        'data-testid': 'form-cancel-action',
      },
      ['Cancel'],
    );
    const form = createElement('form', {}, [grid, createElement('sdoc-form-footer', {}, [saveButton, cancelButton])]);
    const formContainer = createElement('sdoc-form', { 'data-static-editing-form': '' }, [form]);

    const closeForm = () => {
      formContainer.remove();
      nodeElement.style.display = '';
    };

    cancelButton.addEventListener('click', closeForm);
    form.addEventListener('submit', (event) => {
      event.preventDefault();
      const changedFields = [];
      let hasErrors = false;
      const editableFields = Array.from(
        form.querySelectorAll('[data-static-editing-field][contenteditable="true"]'),
      );
      editableFields.forEach((editableField_) => {
        const fieldName = editableField_.dataset.staticEditingField;
        const grammarField = element.fields.find((field_) => field_.title === fieldName);
        const isOnlyInstance =
          editableFields.filter((field_) => field_.dataset.staticEditingField === fieldName).length === 1;
        const newValue = fieldText(editableField_);
        const error = validateField(grammarField, newValue, isOnlyInstance);
        showFieldError(editableField_, error);
        if (error !== null) {
          hasErrors = true;
          return;
        }

        if (editableField_.dataset.staticEditingIndex === 'new') {
          if (newValue.trim().length === 0) return;
          let addedValue = newValue;
          if (AUTHOR_TAGGED_FIELDS.has(fieldName)) {
            if (authorName.length === 0) {
              showFieldError(
                editableField_,
                'Enter your name or initials in the static editing panel at the bottom right before you add a comment.',
              );
              hasErrors = true;
              if (authorInput !== null) authorInput.focus();
              return;
            }
            addedValue = tagWithAuthor(newValue);
          }
          changedFields.push({ name: fieldName, index: null, old_value: null, new_value: addedValue });
          return;
        }
        const index = Number(editableField_.dataset.staticEditingIndex);
        const originalValue = instances.get(fieldName)[index];
        if (newValue !== originalValue) {
          changedFields.push({ name: fieldName, index, old_value: originalValue, new_value: newValue });
        }
      });
      if (hasErrors) return;

      saveChange(node, changedFields).then(() => {
        closeForm();
        renderNodeState(nodeElement, node);
        renderPanel();
      });
    });

    nodeElement.style.display = 'none';
    nodeElement.after(formContainer);
    const firstEditableField = formContainer.querySelector('[contenteditable="true"]');
    if (firstEditableField) firstEditableField.focus();
  }

  function saveChange(node, changedFields) {
    const key = changeKey(node);
    if (changedFields.length === 0) {
      documentChanges.delete(key);
      return store.delete(key);
    }
    const change = {
      key,
      op: 'update_node',
      document_path: DATA.document.path,
      node: { uid: node.uid, mid: node.mid },
      node_type: node.node_type,
      base_hash: node.content_hash,
      fields: changedFields,
      updated_at: new Date().toISOString(),
    };
    documentChanges.set(key, change);
    return store.put(change);
  }

  //
  // The node state: edit button, change marker, and preview.
  //

  function renderNodeState(nodeElement, node) {
    nodeElement.querySelectorAll(':scope > sdoc-static-editing-preview').forEach((preview_) => preview_.remove());
    const change = documentChanges.get(changeKey(node));
    if (!change) {
      nodeElement.removeAttribute('data-static-editing-modified');
      nodeElement.removeAttribute('data-static-editing-current');
      return;
    }
    nodeElement.setAttribute('data-static-editing-modified', '');

    const preview = createElement('sdoc-static-editing-preview', { 'data-testid': 'static-editing-preview' }, [
      createElement('sdoc-static-editing-preview-title', {}, ['Changed locally, not yet applied:']),
    ]);
    change.fields.forEach((field_) => {
      let label = field_.name;
      if (field_.index === null) label += ' (added)';
      else if (field_.new_value.length === 0) label += ' (removed)';
      preview.append(
        createElement(
          'sdoc-static-editing-preview-field',
          {
            'data-field': field_.name,
            'data-removed': field_.index !== null && field_.new_value.length === 0 ? '' : null,
          },
          [
          createElement('b', {}, [label]),
            createElement('pre', {}, [field_.new_value.length > 0 ? field_.new_value : field_.old_value]),
          ],
        ),
      );
    });
    const controls = nodeElement.querySelector(':scope > sdoc-node-controls');
    if (controls) controls.before(preview);
    else nodeElement.append(preview);
  }

  function setUpEditButton(button) {
    if (button.dataset.staticEditingReady === 'true') return;
    button.dataset.staticEditingReady = 'true';
    const nodeElement = button.closest('sdoc-node');
    const node = nodesByHtmlMid.get(button.dataset.staticEditingNode);
    if (!nodeElement || !node) return;

    if (!node.editable) {
      button.title = NOT_EDITABLE_MESSAGES[node.not_editable_reason] || 'Editing is not available';
      return;
    }
    button.classList.remove('action_button--disabled');
    button.title = 'Edit';
    button.href = '#';
    button.addEventListener('click', (event) => {
      event.preventDefault();
      openForm(nodeElement, node);
    });
    renderNodeState(nodeElement, node);
    if (node.html_mid === currentChangedMid) showCurrentChange();
  }

  //
  // The panel with the number of changes, the export, and the discard action.
  //

  let allChanges = [];
  let panel = null;

  function buildExport(changes) {
    return {
      schema: CHANGES_SCHEMA,
      version: CHANGES_VERSION,
      exported_at: new Date().toISOString(),
      changes: changes.map((change_) => ({
        op: change_.op,
        document_path: change_.document_path,
        node: change_.node,
        node_type: change_.node_type,
        base_hash: change_.base_hash,
        fields: change_.fields,
      })),
    };
  }

  // The name of the author becomes part of the file name. The name loses
  // the characters that Windows, Linux, or macOS forbid in a file name:
  // < > : " / \ | ? * and control characters. Whitespace becomes a dash.
  function fileNamePart(text) {
    return text
      .replace(/[<>:"/\\|?*\u0000-\u001F\u007F]/g, '')
      .trim()
      .replace(/\s+/g, '-')
      .replace(/^[.-]+|[.-]+$/g, '');
  }

  function exportFileName() {
    const timestamp = new Date().toISOString().replace(/[:.]/g, '-');
    const author = fileNamePart(authorName);
    return author.length > 0
      ? `strictdoc-changes-${author}-${timestamp}.json`
      : `strictdoc-changes-${timestamp}.json`;
  }

  function downloadExport() {
    store.getAll().then((changes) => {
      const content = JSON.stringify(buildExport(changes), null, 2);
      const blob = new Blob([content], { type: 'application/json' });
      const url = URL.createObjectURL(blob);
      const link = createElement('a', { href: url, download: exportFileName() });
      document.body.append(link);
      link.click();
      link.remove();
      setTimeout(() => URL.revokeObjectURL(url), 1000);
    });
  }

  function discardAll() {
    store.clear().then(() => {
      documentChanges.clear();
      document.querySelectorAll('[data-static-editing-node]').forEach((button_) => {
        const nodeElement = button_.closest('sdoc-node');
        const node = nodesByHtmlMid.get(button_.dataset.staticEditingNode);
        if (nodeElement && node) renderNodeState(nodeElement, node);
      });
      renderPanel();
    });
  }

  let authorInput = null;
  let panelChanges = null;

  function createPanel() {
    panel = createElement('sdoc-static-editing-panel', { 'data-testid': 'static-editing-panel' });

    authorInput = createElement('input', {
      type: 'text',
      value: authorName,
      placeholder: 'Your name or initials',
      'aria-label': 'Your name or initials for comments',
      'data-testid': 'static-editing-author',
    });
    authorInput.addEventListener('input', () => setAuthorName(authorInput.value));
    panel.append(createElement('label', {}, ['Name: ', authorInput]));

    panelChanges = createElement('sdoc-static-editing-panel-changes');
    panel.append(panelChanges);
    document.body.append(panel);
  }

  function renderPanel() {
    return store.getAll().then((changes) => {
      allChanges = changes;
      if (panel === null) createPanel();
      panelChanges.replaceChildren();
      if (changes.length === 0) return;

      const otherDocumentsCount = changes.filter((change_) => change_.document_path !== DATA.document.path).length;
      const countText =
        `${changes.length} local change${changes.length === 1 ? '' : 's'}` +
        (otherDocumentsCount > 0 ? ` (${otherDocumentsCount} in other documents)` : '');

      const exportButton = createElement(
        'button',
        { type: 'button', class: 'action_button', 'data-testid': 'static-editing-export-action' },
        ['Export changes as JSON'],
      );
      exportButton.addEventListener('click', downloadExport);

      // Discarding asks for confirmation in the panel. A browser dialog would
      // block the page for automated tests.
      const discardButton = createElement(
        'button',
        { type: 'button', class: 'action_button', 'data-testid': 'static-editing-discard-action' },
        ['Discard all'],
      );
      const confirmYesButton = createElement(
        'button',
        { type: 'button', class: 'action_button', 'data-testid': 'static-editing-discard-confirm-action' },
        ['Yes'],
      );
      const confirmNoButton = createElement(
        'button',
        { type: 'button', class: 'action_button', 'data-testid': 'static-editing-discard-cancel-action' },
        ['No'],
      );
      const discardConfirm = createElement(
        'sdoc-static-editing-discard-confirm',
        { 'data-testid': 'static-editing-discard-confirm', hidden: '' },
        ['Discard all changes? ', confirmYesButton, confirmNoButton],
      );
      discardButton.addEventListener('click', () => {
        discardButton.hidden = true;
        discardConfirm.hidden = false;
        confirmNoButton.focus();
      });
      confirmNoButton.addEventListener('click', () => {
        discardConfirm.hidden = true;
        discardButton.hidden = false;
      });
      confirmYesButton.addEventListener('click', discardAll);

      panelChanges.append(
        createElement('sdoc-static-editing-panel-count', { 'data-testid': 'static-editing-change-count' }, [countText]),
        ...createNavigation(),
        exportButton,
        discardButton,
        discardConfirm,
      );
    });
  }

  //
  // The navigation between the changed nodes of the document, similar to the
  // search of a browser. It wraps around at the first and the last node.
  //

  // The stored changes, not the DOM, define the list of changed nodes. A
  // large document loads its content in chunks, so the node of a change can
  // be missing from the DOM.
  let currentChangedMid = null;
  let navigationPosition = null;

  function changedNodes() {
    // DATA.nodes is in document order.
    return DATA.nodes.filter((node_) => documentChanges.has(changeKey(node_)));
  }

  function nodeElementForMid(htmlMid) {
    const button = document.querySelector(`[data-static-editing-node="${CSS.escape(htmlMid)}"]`);
    return button ? button.closest('sdoc-node') : null;
  }

  // Each unloaded chunk placeholder lists the MIDs and the anchors of its
  // nodes position for position (see document_chunk_lazy_placeholder).
  function anchorOfUnloadedNode(htmlMid) {
    for (const placeholder_ of document.querySelectorAll('[data-node-mids][data-anchors]')) {
      const index = placeholder_.dataset.nodeMids.split(' ').indexOf(htmlMid);
      if (index >= 0) return placeholder_.dataset.anchors.split(' ')[index] || null;
    }
    return null;
  }

  function showCurrentChange() {
    document
      .querySelectorAll('sdoc-node[data-static-editing-current]')
      .forEach((node_) => node_.removeAttribute('data-static-editing-current'));
    if (currentChangedMid === null) return true;
    const nodeElement = nodeElementForMid(currentChangedMid);
    if (!nodeElement) return false;
    nodeElement.setAttribute('data-static-editing-current', '');
    nodeElement.scrollIntoView({ block: 'center' });
    return true;
  }

  function renderNavigationPosition() {
    if (navigationPosition === null) return;
    const nodes = changedNodes();
    const index = nodes.findIndex((node_) => node_.html_mid === currentChangedMid);
    navigationPosition.textContent = `${index < 0 ? '–' : index + 1} / ${nodes.length}`;
  }

  function jumpToChange(step) {
    const nodes = changedNodes();
    if (nodes.length === 0) return;
    const index = nodes.findIndex((node_) => node_.html_mid === currentChangedMid);
    let nextIndex;
    if (index < 0) nextIndex = step > 0 ? 0 : nodes.length - 1;
    else nextIndex = (index + step + nodes.length) % nodes.length;
    currentChangedMid = nodes[nextIndex].html_mid;
    renderNavigationPosition();
    if (showCurrentChange()) return;

    // The node is in a chunk that is not loaded yet. The chunk navigation of
    // the document screen (toc_chunk_navigation.js) loads the chunk on a
    // hashchange. replaceState keeps the browser history free of the jumps.
    // setUpEditButton() marks the node once the chunk is inserted.
    const anchor = anchorOfUnloadedNode(currentChangedMid);
    if (anchor === null) return;
    window.history.replaceState(null, '', `#${encodeURIComponent(anchor)}`);
    window.dispatchEvent(new HashChangeEvent('hashchange'));
  }

  function createNavigation() {
    navigationPosition = null;
    if (documentChanges.size === 0) return [];
    navigationPosition = createElement('sdoc-static-editing-navigation-position', {
      'data-testid': 'static-editing-navigation-position',
    });
    const previousButton = createElement(
      'button',
      {
        type: 'button',
        class: 'action_button',
        title: 'Previous change',
        'aria-label': 'Previous change',
        'data-testid': 'static-editing-previous-change-action',
      },
      ['\u25B2'],
    );
    const nextButton = createElement(
      'button',
      {
        type: 'button',
        class: 'action_button',
        title: 'Next change',
        'aria-label': 'Next change',
        'data-testid': 'static-editing-next-change-action',
      },
      ['\u25BC'],
    );
    previousButton.addEventListener('click', () => jumpToChange(-1));
    nextButton.addEventListener('click', () => jumpToChange(1));
    renderNavigationPosition();
    return [
      createElement('sdoc-static-editing-navigation', { 'data-testid': 'static-editing-navigation' }, [
        previousButton,
        navigationPosition,
        nextButton,
      ]),
    ];
  }

  //
  // Start.
  //

  store
    .getAll()
    .then((changes) => {
      changes
        .filter((change_) => change_.document_path === DATA.document.path)
        .forEach((change_) => documentChanges.set(change_.key, change_));
    })
    .then(() => {
      // Large documents load their content in chunks. onInsert also covers
      // the nodes of chunks that are inserted later.
      window.StrictDoc.onInsert('[data-static-editing-node]', setUpEditButton);
      return renderPanel();
    });

  // Intentional cross-script contract for end-to-end tests and integrations:
  // read the changes of the project in the export format.
  window.StrictDoc.staticEditing = {
    getExport: () => store.getAll().then(buildExport),
    getChangeCount: () => allChanges.length,
    getExportFileName: exportFileName,
  };
})();
