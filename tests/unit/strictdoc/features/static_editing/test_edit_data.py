from strictdoc.backend.sdoc.document_reference import DocumentReference
from strictdoc.backend.sdoc.models.node import SDocNode
from strictdoc.core.document_tree import DocumentTree
from strictdoc.core.traceability_index import TraceabilityIndex
from strictdoc.core.traceability_index_builder import TraceabilityIndexBuilder
from strictdoc.features.static_editing.edit_data import (
    NotEditableReason,
    compute_node_content_hash,
    get_node_not_editable_reason,
)
from tests.unit.helpers.document_builder import DocumentBuilder


def _build_traceability_index(
    document_builder: DocumentBuilder,
) -> TraceabilityIndex:
    document = document_builder.build()
    for requirement_ in document_builder.requirements:
        # The document builder does not set the including document reference
        # that the parser sets for every node.
        requirement_.ng_including_document_reference = DocumentReference()
    document_tree = DocumentTree(
        file_tree=[],
        document_list=[document],
        map_docs_by_paths={},
        map_docs_by_rel_paths={},
        map_grammars_by_filenames={},
    )
    return TraceabilityIndexBuilder.create_from_document_tree(
        document_tree,
        project_config=document_builder.project_config,
    )


def test_01_content_hash_is_stable_for_equal_content() -> None:
    document_builder = DocumentBuilder()
    requirement_1: SDocNode = document_builder.add_requirement("REQ-001")
    requirement_2: SDocNode = document_builder.add_requirement("REQ-001")

    assert compute_node_content_hash(
        requirement_1
    ) == compute_node_content_hash(requirement_2)
    assert compute_node_content_hash(requirement_1).startswith("sha256:")


def test_02_content_hash_changes_when_a_field_changes() -> None:
    document_builder = DocumentBuilder()
    requirement: SDocNode = document_builder.add_requirement("REQ-001")
    hash_before = compute_node_content_hash(requirement)

    requirement.set_field_value(
        field_name="STATEMENT",
        form_field_index=0,
        value="System X shall do Z",
    )

    assert compute_node_content_hash(requirement) != hash_before


def test_10_node_with_uid_is_editable() -> None:
    document_builder = DocumentBuilder()
    document_builder.add_requirement("REQ-001")
    traceability_index = _build_traceability_index(document_builder)

    requirement = document_builder.requirements[0]
    assert get_node_not_editable_reason(requirement, traceability_index) is None


def test_11_node_without_uid_and_generated_mid_is_not_editable() -> None:
    document_builder = DocumentBuilder()
    document_builder.add_requirement(None)
    traceability_index = _build_traceability_index(document_builder)

    requirement = document_builder.requirements[0]
    assert requirement.mid_permanent is False
    assert (
        get_node_not_editable_reason(requirement, traceability_index)
        == NotEditableReason.NO_STABLE_IDENTIFIER
    )


def test_12_node_without_uid_and_permanent_mid_is_editable() -> None:
    document_builder = DocumentBuilder()
    document_builder.add_requirement(None)
    traceability_index = _build_traceability_index(document_builder)

    requirement = document_builder.requirements[0]
    requirement.mid_permanent = True
    assert get_node_not_editable_reason(requirement, traceability_index) is None


def test_13_autogenerated_node_is_not_editable() -> None:
    document_builder = DocumentBuilder()
    document_builder.add_requirement("REQ-001")
    traceability_index = _build_traceability_index(document_builder)

    requirement = document_builder.requirements[0]
    requirement.autogen = True
    assert (
        get_node_not_editable_reason(requirement, traceability_index)
        == NotEditableReason.AUTOGENERATED
    )
