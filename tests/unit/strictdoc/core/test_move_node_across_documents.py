# Regression test: SDocParsingProcessor.process_requirement() assigns every
# node of a document the SAME DocumentReference instance (by reference, not
# a copy), see strictdoc/backend/sdoc/processor.py. An earlier version of
# MoveNodeAcrossDocumentsCommand called
# moved_node.ng_document_reference.set_document(destination) directly,
# which mutated that shared instance in place and silently repointed every
# other, untouched node of the source document to the destination too.
# DocumentBuilder gives each node its own DocumentReference instance, so it
# does not reproduce this sharing; the test below simulates it explicitly.
def test_move_node_across_documents_does_not_corrupt_sibling_document_reference():
    traceability_index, document_1, doc1_reqs, _, doc2_reqs = (
        _build_two_document_index(
            doc1_requirements=("REQ-001", "REQ-002"),
            doc2_requirements=("REQ-003",),
        )
    )
    moved_requirement, sibling_requirement = doc1_reqs
    target_requirement = doc2_reqs[0]

    shared_reference = DocumentReference()
    shared_reference.set_document(document_1)
    moved_requirement.ng_document_reference = shared_reference
    sibling_requirement.ng_document_reference = shared_reference

    command = MoveNodeAcrossDocumentsCommand(
        moved_node=moved_requirement,
        target_node=target_requirement,
        whereto=NodeCreationOrder.AFTER,
        traceability_index=traceability_index,
    )
    command.perform()

    assert moved_requirement.get_document() is command.destination_document
    # The sibling shared the same DocumentReference instance before the
    # move and must still resolve to the source document afterward.
    assert sibling_requirement.get_document() is document_1


def test_move_node_within_same_document_reorders_without_reference_change():
    # The same modal flow also handles reordering within one document
    # (task.md: "before"/"after" any node at any level, same document or
    # not). This must behave like a plain reorder: no document_reference
    # rewrite, and source_document/destination_document both point at the
    # one document, so the router does not write it twice.
    traceability_index, document_1, doc1_reqs, _, _ = _build_two_document_index(
        doc1_requirements=("REQ-001", "REQ-002"),
        doc2_requirements=("REQ-003",),
    )
    first_requirement, second_requirement = doc1_reqs

    command = MoveNodeAcrossDocumentsCommand(
        moved_node=first_requirement,
        target_node=second_requirement,
        whereto=NodeCreationOrder.AFTER,
        traceability_index=traceability_index,
    )
    command.perform()

    assert first_requirement.get_document() is document_1
    assert document_1.section_contents == [
        second_requirement,
        first_requirement,
    ]
    assert command.source_document is document_1
    assert command.destination_document is document_1


@pytest.mark.parametrize(
    "whereto",
    [
        NodeCreationOrder.BEFORE,
        NodeCreationOrder.AFTER,
        NodeCreationOrder.CHILD,
    ],
)
def test_move_node_already_at_target_location_is_no_op(whereto: str):
    traceability_index, document_1, doc1_reqs, _, _ = _build_two_document_index(
        doc1_requirements=("REQ-001", "REQ-002"),
        doc2_requirements=("REQ-003",),
    )
    first_requirement, second_requirement = doc1_reqs

    if whereto == NodeCreationOrder.BEFORE:
        moved_requirement = first_requirement
        target_node = second_requirement
    elif whereto == NodeCreationOrder.AFTER:
        moved_requirement = second_requirement
        target_node = first_requirement
    else:
        first_requirement.is_composite = True
        document_1.section_contents.remove(second_requirement)
        first_requirement.section_contents.append(second_requirement)
        second_requirement.parent = first_requirement
        moved_requirement = second_requirement
        target_node = first_requirement

    parent_contents_before_move = list(
        moved_requirement.parent.section_contents
    )
    last_updated_before_move = traceability_index.index_last_updated
    command = MoveNodeAcrossDocumentsCommand(
        moved_node=moved_requirement,
        target_node=target_node,
        whereto=whereto,
        traceability_index=traceability_index,
    )

    command.perform()

    assert not command.move_was_performed
    assert moved_requirement.parent.section_contents == (
        parent_contents_before_move
    )
    assert traceability_index.index_last_updated == last_updated_before_move


