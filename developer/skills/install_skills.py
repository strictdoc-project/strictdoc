"""
Generate Claude and Codex skill pointer stubs for the project skills.

The project skills come from two sources:

- developer/skills/<name>/: skills maintained in this repository.
- submodules/<repo>/: skills maintained in their own Git repositories and
  included as Git submodules. SUBMODULE_SKILLS below lists them.

The agent-specific directories are gitignored in this repo, so each
developer/agent regenerates the small SKILL.md stubs Claude Code and Codex
need for skill discovery by running this script locally:

    git submodule update --init
    python developer/skills/install_skills.py

Convention this script relies on: each skill lives in its own directory,
and its main file is named SKILL.md, e.g.
developer/skills/<name>/SKILL.md or submodules/technical_writing_skill/SKILL.md.
Any other files in that directory are supporting material the main file may
reference; they are not copied or parsed here.

Safe to re-run any time: it regenerates all stubs deterministically and
removes stale stubs for skills that no longer exist, but only removes
directories whose SKILL.md was itself generated by this script (marked with
POINTER_MARKER below), so it never touches a skill someone authored directly
in an agent-specific directory.
"""

import shutil
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
SKILLS_SRC = REPO_ROOT / "developer" / "skills"
SKILLS_DESTINATIONS = (
    REPO_ROOT / ".claude" / "skills",
    REPO_ROOT / ".agents" / "skills",
)

# Skills stored in Git submodules: skill name -> submodule directory.
SUBMODULE_SKILLS: dict[str, Path] = {
    "technical-writing-guide": (
        REPO_ROOT / "submodules" / "technical_writing_skill"
    ),
}

POINTER_MARKER = "<!-- generated by developer/skills/install_skills.py -->"

STUB_BODY_TEMPLATE = """{marker}

This is a pointer file, not the skill itself. The actual instructions and
any supporting files they reference live under `{skill_path}/`,
so they are tracked in git and reusable by other agents/tools.

Read `{skill_path}/SKILL.md` in full and follow it,
including any sibling files in that directory it points to.
"""


def main() -> None:
    if not SKILLS_SRC.is_dir():
        raise SystemExit(f"{SKILLS_SRC} not found")

    skill_sources = _collect_skill_sources()
    for skills_dst in SKILLS_DESTINATIONS:
        installed = set()
        for name_, skill_dir_ in skill_sources.items():
            if _install_skill(name_, skill_dir_, skills_dst):
                installed.add(name_)

        _remove_stale_stubs(skills_dst, installed)


def _collect_skill_sources() -> dict[str, Path]:
    skill_sources: dict[str, Path] = {
        path_.name: path_
        for path_ in sorted(SKILLS_SRC.iterdir())
        if path_.is_dir() and (path_ / "SKILL.md").is_file()
    }

    for name_, skill_dir_ in SUBMODULE_SKILLS.items():
        if name_ in skill_sources:
            raise SystemExit(
                f"skill {name_} is defined twice: "
                f"{_relative(skill_sources[name_])} and "
                f"{_relative(skill_dir_)}"
            )
        if not (skill_dir_ / "SKILL.md").is_file():
            print(  # noqa: T201
                f"skip {name_}: {_relative(skill_dir_)}/SKILL.md not found. "
                "Run: git submodule update --init "
                f"{_relative(skill_dir_)}"
            )
            continue
        skill_sources[name_] = skill_dir_

    return skill_sources


def _install_skill(name: str, skill_dir: Path, skills_dst: Path) -> bool:
    main_file = skill_dir / "SKILL.md"
    frontmatter = _extract_frontmatter(main_file.read_text())
    if frontmatter is None:
        print(  # noqa: T201
            f"skip {name}: {_relative(main_file)} has no frontmatter"
        )
        return False

    stub_dir = skills_dst / name
    stub_dir.mkdir(parents=True, exist_ok=True)
    stub_path = stub_dir / "SKILL.md"
    stub_path.write_text(
        frontmatter
        + "\n"
        + STUB_BODY_TEMPLATE.format(
            marker=POINTER_MARKER, skill_path=_relative(skill_dir)
        )
    )
    print(f"wrote {_relative(stub_path)}")  # noqa: T201
    return True


def _extract_frontmatter(text: str) -> str | None:
    if not text.startswith("---"):
        return None
    lines = text.splitlines(keepends=True)
    for index_ in range(1, len(lines)):
        if lines[index_].strip() == "---":
            return "".join(lines[: index_ + 1])
    return None


def _remove_stale_stubs(skills_dst: Path, installed_names: set[str]) -> None:
    if not skills_dst.is_dir():
        return
    for stub_dir_ in skills_dst.iterdir():
        if not stub_dir_.is_dir() or stub_dir_.name in installed_names:
            continue
        stub_path = stub_dir_ / "SKILL.md"
        if stub_path.is_file() and POINTER_MARKER in stub_path.read_text():
            shutil.rmtree(stub_dir_)
            print(f"removed stale {_relative(stub_dir_)}")  # noqa: T201


def _relative(path: Path) -> str:
    return path.relative_to(REPO_ROOT).as_posix()


if __name__ == "__main__":
    main()
