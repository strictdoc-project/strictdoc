"""
Builds the static editing data of a document: the raw source values of all
nodes, the document grammar, and the identity and content hash of each node.

The browser-side static editor reads this data to render edit forms. The
command that applies the exported changes reuses compute_node_content_hash()
to detect nodes whose source has changed since the export.

@relation(SDOC-SRS-214, scope=file)
"""

import json
from typing import Any, Dict, List, Optional

from strictdoc.backend.sdoc.models.document import SDocDocument
from strictdoc.backend.sdoc.models.document_grammar import DocumentGrammar
from strictdoc.backend.sdoc.models.grammar_element import (
    GrammarElement,
    GrammarElementFieldMultipleChoice,
    GrammarElementFieldSingleChoice,
)
from strictdoc.backend.sdoc.models.node import SDocNode
from strictdoc.core.document_meta import DocumentMeta
from strictdoc.core.traceability_index import TraceabilityIndex
from strictdoc.helpers.cast import assert_cast
from strictdoc.helpers.sha256 import get_sha256

STATIC_EDITING_DATA_SCHEMA = "strictdoc-static-editing-data"
STATIC_EDITING_DATA_VERSION = 1


class NotEditableReason:
    AUTOGENERATED = "autogenerated"
    MANAGED_BY_SOURCE_CODE = "managed_by_source_code"
    NO_STABLE_IDENTIFIER = "no_stable_identifier"


def compute_node_content_hash(node: SDocNode) -> str:
    """
    Compute a SHA-256 hash over the node type and the source values of all
    fields that originate from the document. The hash changes when any of
    these values changes.
    """
    hashed_content: List[Any] = [
        node.node_type,
        [
            [field_.field_name, field_.get_text_value()]
            for field_ in node.enumerate_fields()
            if field_.is_document_origin()
        ],
    ]
    serialized_content = json.dumps(
        hashed_content, ensure_ascii=False, separators=(",", ":")
    )
    return "sha256:" + get_sha256(serialized_content.encode("utf-8"))


def get_node_not_editable_reason(
    node: SDocNode, traceability_index: TraceabilityIndex
) -> Optional[str]:
    """
    Return None if the static editor can edit the node, otherwise the reason
    why it cannot. A node is editable only if it has a UID or a MID that is
    stored in the source file. A MID that StrictDoc generates at build time
    changes with every export and cannot identify the node later.
    """
    if not traceability_index.can_edit_node(node):
        return NotEditableReason.AUTOGENERATED
    if node.is_managed_by_source_code():
        return NotEditableReason.MANAGED_BY_SOURCE_CODE
    if node.reserved_uid is None and not node.mid_permanent:
        return NotEditableReason.NO_STABLE_IDENTIFIER
    return None


def build_document_edit_data(
    document: SDocDocument, traceability_index: TraceabilityIndex
) -> Dict[str, Any]:
    document_meta: DocumentMeta = assert_cast(document.meta, DocumentMeta)
    document_grammar: DocumentGrammar = assert_cast(
        document.grammar, DocumentGrammar
    )

    nodes_data: List[Dict[str, Any]] = []
    document_iterator = traceability_index.get_document_iterator(document)
    for node_, _ in document_iterator.all_content(print_fragments=False):
        if not isinstance(node_, SDocNode):
            continue
        if node_.get_document() is not document:
            continue
        nodes_data.append(_build_node_edit_data(node_, traceability_index))

    return {
        "schema": STATIC_EDITING_DATA_SCHEMA,
        "version": STATIC_EDITING_DATA_VERSION,
        "document": {
            "path": document_meta.input_doc_rel_path.relative_path_posix,
            "title": document.title,
            "mid": (
                document.reserved_mid.get_string_value()
                if document.mid_permanent
                else None
            ),
            "markup": document.config.get_markup(),
        },
        "grammar": {
            "elements": [
                _build_grammar_element_data(element_)
                for element_ in document_grammar.elements
            ],
        },
        "nodes": nodes_data,
    }


def _build_node_edit_data(
    node: SDocNode, traceability_index: TraceabilityIndex
) -> Dict[str, Any]:
    not_editable_reason = get_node_not_editable_reason(node, traceability_index)
    node_data: Dict[str, Any] = {
        "html_mid": node.reserved_mid.get_string_value(),
        "node_type": node.node_type,
        "uid": node.reserved_uid,
        "mid": (
            node.reserved_mid.get_string_value() if node.mid_permanent else None
        ),
        "editable": not_editable_reason is None,
        "not_editable_reason": not_editable_reason,
    }
    if not_editable_reason is None:
        node_data["content_hash"] = compute_node_content_hash(node)
        node_data["fields"] = [
            {"name": field_.field_name, "value": field_.get_text_value()}
            for field_ in node.enumerate_fields()
            if field_.is_document_origin()
        ]
    return node_data


def _build_grammar_element_data(element: GrammarElement) -> Dict[str, Any]:
    fields_data: List[Dict[str, Any]] = []
    for field_ in element.fields:
        field_data: Dict[str, Any] = {
            "title": field_.title,
            "human_title": field_.human_title,
            "type": field_.gef_type,
            "required": field_.required,
            "multiline": element.is_field_multiline(field_.title),
        }
        if isinstance(
            field_,
            (
                GrammarElementFieldSingleChoice,
                GrammarElementFieldMultipleChoice,
            ),
        ):
            field_data["options"] = list(field_.options)
        fields_data.append(field_data)
    return {
        "tag": element.tag,
        "fields": fields_data,
    }
