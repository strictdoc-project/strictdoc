// static_editing.js
//
// The static editor of the STATIC_EDITING feature. It runs on the DOCUMENT
// screen of a static HTML export, where no StrictDoc server is available.
//
// - The export writes the static editing data of the document into
//   <document>.edit.js. The script reads it from
//   window.StrictDocStaticEditingData.
// - The edit button of a node opens a form with the source values of the
//   node fields. The form reuses the markup and styles of the server forms.
// - Saving the form stores a change in the IndexedDB of the browser. The
//   change survives a page reload.
// - The panel at the bottom of the page exports all stored changes of the
//   project as one JSON file. A StrictDoc command applies the JSON file to the
//   SDoc source files.
//
// @relation(SDOC-SRS-215, scope=file)

(() => {
  const DATA = window.StrictDocStaticEditingData;
  if (!DATA) {
    console.warn('static_editing.js: the static editing data is missing.');
    return;
  }

  const CHANGES_SCHEMA = 'strictdoc-static-editing-changes';
  const CHANGES_VERSION = 1;
  const DATABASE_VERSION = 1;
  const STORE_NAME = 'changes';

  // Fields that the static editor shows, but does not let the user edit.
  // A changed UID or MID would break the identity of the node and its
  // incoming relations.
  const READ_ONLY_FIELDS = new Set(['UID', 'MID']);

  const NOT_EDITABLE_MESSAGES = {
    autogenerated: 'Editing is disabled for autogenerated nodes',
    managed_by_source_code: 'Editing is disabled for nodes managed by source code',
    no_stable_identifier:
      'Editing requires a UID or a MID in the source file. See the "Static editing" section of the StrictDoc user guide.',
  };

  const nodesByHtmlMid = new Map(DATA.nodes.map((node_) => [node_.html_mid, node_]));
  const elementsByTag = new Map(DATA.grammar.elements.map((element_) => [element_.tag, element_]));

  // Changes of this document, by change key. Kept in sync with the store.
  const documentChanges = new Map();

  //
  // Change keys and the change store.
  //

  function nodeKey(node) {
    if (node.uid !== null) return `uid:${node.uid}`;
    return `mid:${node.mid}`;
  }

  function changeKey(node) {
    return `${DATA.document.path}#${nodeKey(node)}`;
  }

  function projectHash() {
    const meta = document.querySelector('meta[name="strictdoc-project-hash"]');
    return meta ? meta.content : 'default';
  }

  // The store of all changes of the project. A project published on a shared
  // origin, for example GitHub Pages, gets its own database name.
  const store = createStore(`strictdoc-static-editing-${projectHash()}`);

  function createStore(databaseName) {
    let databasePromise = null;

    function openDatabase() {
      if (databasePromise === null) {
        databasePromise = new Promise((resolve, reject) => {
          const request = window.indexedDB.open(databaseName, DATABASE_VERSION);
          request.onupgradeneeded = () => {
            request.result.createObjectStore(STORE_NAME, { keyPath: 'key' });
          };
          request.onsuccess = () => resolve(request.result);
          request.onerror = () => reject(request.error);
        });
      }
      return databasePromise;
    }

    function run(mode, action) {
      return openDatabase().then(
        (database) =>
          new Promise((resolve, reject) => {
            const transaction = database.transaction(STORE_NAME, mode);
            const request = action(transaction.objectStore(STORE_NAME));
            transaction.oncomplete = () => resolve(request ? request.result : undefined);
            transaction.onerror = () => reject(transaction.error);
          }),
      );
    }

    // The memory store keeps the changes until the page reloads. It is used
    // when the browser offers no IndexedDB, for example in a private window
    // of some browsers.
    const memory = new Map();
    let useMemory = !window.indexedDB;

    function withFallback(databaseAction, memoryAction) {
      if (useMemory) return Promise.resolve(memoryAction());
      return databaseAction().catch((error) => {
        console.warn('static_editing.js: IndexedDB is not available, changes are kept until the page reloads.', error);
        useMemory = true;
        return memoryAction();
      });
    }

    return {
      getAll: () =>
        withFallback(
          () => run('readonly', (objectStore) => objectStore.getAll()),
          () => Array.from(memory.values()),
        ),
      put: (change) =>
        withFallback(
          () => run('readwrite', (objectStore) => objectStore.put(change)),
          () => memory.set(change.key, change),
        ),
      delete: (key) =>
        withFallback(
          () => run('readwrite', (objectStore) => objectStore.delete(key)),
          () => memory.delete(key),
        ),
      clear: () =>
        withFallback(
          () => run('readwrite', (objectStore) => objectStore.clear()),
          () => memory.clear(),
        ),
    };
  }

  //
  // Field values.
  //

  // The first value of each field. Multi-instance fields, for example
  // COMMENT, are read-only in the static editor.
  function originalFieldValues(node) {
    const values = new Map();
    const counts = new Map();
    node.fields.forEach((field_) => {
      counts.set(field_.name, (counts.get(field_.name) || 0) + 1);
      if (!values.has(field_.name)) values.set(field_.name, field_.value);
    });
    return { values, counts };
  }

  function currentFieldValue(node, fieldName, originalValue) {
    const change = documentChanges.get(changeKey(node));
    if (change) {
      const changedField = change.fields.find((field_) => field_.name === fieldName);
      if (changedField) return changedField.new_value;
    }
    return originalValue;
  }

  //
  // The edit form.
  //

  function createElement(tagName, attributes = {}, children = []) {
    const element = document.createElement(tagName);
    Object.entries(attributes).forEach(([name_, value_]) => {
      if (value_ !== null && value_ !== undefined) element.setAttribute(name_, value_);
    });
    children.forEach((child_) => element.append(child_));
    return element;
  }

  function createFieldRow(grammarField, value, editable) {
    const fieldType = grammarField.multiline ? 'multiline' : 'singleline';
    const label = editable ? grammarField.title : `${grammarField.title} (READ-ONLY)`;
    const inputName = `static_editing_field[${grammarField.title}]`;

    const editableField = createElement('sdoc-contenteditable', {
      'data-js-editable-field': '',
      role: 'textbox',
      'data-field-type': fieldType,
      contenteditable: editable ? 'true' : 'false',
      id: inputName,
      placeholder: `Enter ${grammarField.title} here...`,
      'data-field-label': grammarField.required ? `${label} *` : label,
      'data-static-editing-field': grammarField.title,
      'data-testid': `form-field-${grammarField.title}`,
    });
    editableField.textContent = value;

    const hiddenInput = createElement('input', { type: 'hidden', name: inputName, value });

    const row = createElement('sdoc-form-row', {}, [
      createElement('sdoc-form-row-aside'),
      createElement('sdoc-form-row-main', {}, [createElement('sdoc-form-field', {}, [editableField, hiddenInput])]),
      createElement('sdoc-form-row-aside'),
    ]);
    if (grammarField.options) {
      row.dataset.staticEditingOptions = JSON.stringify(grammarField.options);
    }
    return row;
  }

  function fieldText(editableField) {
    // editable_field.js keeps the hidden input next to the field in sync
    // with the field text.
    const hiddenInput = editableField.parentElement.querySelector('input[type="hidden"]');
    return hiddenInput ? hiddenInput.value : editableField.innerText;
  }

  function validateField(grammarField, value) {
    if (grammarField.required && value.trim().length === 0) {
      return `${grammarField.title} must not be empty. If there is no appropriate value for this field yet, enter TBD (to be done) or TBC (to be confirmed).`;
    }
    if (grammarField.options && value.trim().length > 0) {
      const values =
        grammarField.type === 'MultipleChoice'
          ? value.split(',').map((value_) => value_.trim())
          : [value.trim()];
      const invalidValues = values.filter((value_) => !grammarField.options.includes(value_));
      if (invalidValues.length > 0) {
        return `Invalid value: ${invalidValues.join(', ')}. Valid values: ${grammarField.options.join(', ')}.`;
      }
    }
    return null;
  }

  function showFieldError(editableField, message) {
    const formField = editableField.closest('sdoc-form-field');
    formField.querySelectorAll('sdoc-form-error').forEach((error_) => error_.remove());
    if (message === null) {
      editableField.removeAttribute('errors');
      return;
    }
    editableField.setAttribute('errors', 'true');
    formField.append(createElement('sdoc-form-error', {}, [message]));
  }

  function openForm(nodeElement, node) {
    if (nodeElement.parentElement.querySelector('sdoc-form[data-static-editing-form]')) return;

    const element = elementsByTag.get(node.node_type);
    const { values, counts } = originalFieldValues(node);

    const grid = createElement('sdoc-form-grid');
    element.fields.forEach((grammarField_) => {
      if (!values.has(grammarField_.title) && READ_ONLY_FIELDS.has(grammarField_.title)) return;
      const originalValue = values.has(grammarField_.title) ? values.get(grammarField_.title) : '';
      const editable =
        !READ_ONLY_FIELDS.has(grammarField_.title) && (counts.get(grammarField_.title) || 0) <= 1;
      grid.append(
        createFieldRow(grammarField_, currentFieldValue(node, grammarField_.title, originalValue), editable),
      );
    });

    const saveButton = createElement(
      'button',
      {
        type: 'submit',
        class: 'action_button',
        'data-action-type': 'submit',
        'data-testid': 'form-submit-action',
      },
      ['Save'],
    );
    const cancelButton = createElement(
      'button',
      {
        type: 'button',
        class: 'action_button',
        'data-action-type': 'cancel',
        'data-testid': 'form-cancel-action',
      },
      ['Cancel'],
    );
    const form = createElement('form', {}, [grid, createElement('sdoc-form-footer', {}, [saveButton, cancelButton])]);
    const formContainer = createElement('sdoc-form', { 'data-static-editing-form': '' }, [form]);

    const closeForm = () => {
      formContainer.remove();
      nodeElement.style.display = '';
    };

    cancelButton.addEventListener('click', closeForm);
    form.addEventListener('submit', (event) => {
      event.preventDefault();
      const changedFields = [];
      let hasErrors = false;
      form.querySelectorAll('[data-static-editing-field][contenteditable="true"]').forEach((editableField_) => {
        const fieldName = editableField_.dataset.staticEditingField;
        const grammarField = element.fields.find((field_) => field_.title === fieldName);
        const newValue = fieldText(editableField_);
        const error = validateField(grammarField, newValue);
        showFieldError(editableField_, error);
        if (error !== null) {
          hasErrors = true;
          return;
        }
        const originalValue = values.has(fieldName) ? values.get(fieldName) : '';
        if (newValue !== originalValue) {
          changedFields.push({ name: fieldName, old_value: originalValue, new_value: newValue });
        }
      });
      if (hasErrors) return;

      saveChange(node, changedFields).then(() => {
        closeForm();
        renderNodeState(nodeElement, node);
        renderPanel();
      });
    });

    nodeElement.style.display = 'none';
    nodeElement.after(formContainer);
    const firstEditableField = formContainer.querySelector('[contenteditable="true"]');
    if (firstEditableField) firstEditableField.focus();
  }

  function saveChange(node, changedFields) {
    const key = changeKey(node);
    if (changedFields.length === 0) {
      documentChanges.delete(key);
      return store.delete(key);
    }
    const change = {
      key,
      op: 'update_node',
      document_path: DATA.document.path,
      node: { uid: node.uid, mid: node.mid },
      node_type: node.node_type,
      base_hash: node.content_hash,
      fields: changedFields,
      updated_at: new Date().toISOString(),
    };
    documentChanges.set(key, change);
    return store.put(change);
  }

  //
  // The node state: edit button, change marker, and preview.
  //

  function renderNodeState(nodeElement, node) {
    nodeElement.querySelectorAll(':scope > sdoc-static-editing-preview').forEach((preview_) => preview_.remove());
    const change = documentChanges.get(changeKey(node));
    if (!change) {
      nodeElement.removeAttribute('data-static-editing-modified');
      return;
    }
    nodeElement.setAttribute('data-static-editing-modified', '');

    const preview = createElement('sdoc-static-editing-preview', { 'data-testid': 'static-editing-preview' }, [
      createElement('sdoc-static-editing-preview-title', {}, ['Changed locally, not yet applied:']),
    ]);
    change.fields.forEach((field_) => {
      preview.append(
        createElement('sdoc-static-editing-preview-field', { 'data-field': field_.name }, [
          createElement('b', {}, [field_.name]),
          createElement('pre', {}, [field_.new_value]),
        ]),
      );
    });
    const controls = nodeElement.querySelector(':scope > sdoc-node-controls');
    if (controls) controls.before(preview);
    else nodeElement.append(preview);
  }

  function setUpEditButton(button) {
    if (button.dataset.staticEditingReady === 'true') return;
    button.dataset.staticEditingReady = 'true';
    const nodeElement = button.closest('sdoc-node');
    const node = nodesByHtmlMid.get(button.dataset.staticEditingNode);
    if (!nodeElement || !node) return;

    if (!node.editable) {
      button.title = NOT_EDITABLE_MESSAGES[node.not_editable_reason] || 'Editing is not available';
      return;
    }
    button.classList.remove('action_button--disabled');
    button.title = 'Edit';
    button.href = '#';
    button.addEventListener('click', (event) => {
      event.preventDefault();
      openForm(nodeElement, node);
    });
    renderNodeState(nodeElement, node);
  }

  //
  // The panel with the number of changes, the export, and the discard action.
  //

  let allChanges = [];
  let panel = null;

  function buildExport(changes) {
    return {
      schema: CHANGES_SCHEMA,
      version: CHANGES_VERSION,
      exported_at: new Date().toISOString(),
      changes: changes.map((change_) => ({
        op: change_.op,
        document_path: change_.document_path,
        node: change_.node,
        node_type: change_.node_type,
        base_hash: change_.base_hash,
        fields: change_.fields,
      })),
    };
  }

  function downloadExport() {
    store.getAll().then((changes) => {
      const content = JSON.stringify(buildExport(changes), null, 2);
      const blob = new Blob([content], { type: 'application/json' });
      const url = URL.createObjectURL(blob);
      const timestamp = new Date().toISOString().replace(/[:.]/g, '-');
      const link = createElement('a', { href: url, download: `strictdoc-changes-${timestamp}.json` });
      document.body.append(link);
      link.click();
      link.remove();
      setTimeout(() => URL.revokeObjectURL(url), 1000);
    });
  }

  function discardAll() {
    store.clear().then(() => {
      documentChanges.clear();
      document.querySelectorAll('[data-static-editing-node]').forEach((button_) => {
        const nodeElement = button_.closest('sdoc-node');
        const node = nodesByHtmlMid.get(button_.dataset.staticEditingNode);
        if (nodeElement && node) renderNodeState(nodeElement, node);
      });
      renderPanel();
    });
  }

  function renderPanel() {
    return store.getAll().then((changes) => {
      allChanges = changes;
      if (panel === null) {
        panel = createElement('sdoc-static-editing-panel', { 'data-testid': 'static-editing-panel' });
        document.body.append(panel);
      }
      panel.replaceChildren();
      panel.hidden = changes.length === 0;
      if (changes.length === 0) return;

      const otherDocumentsCount = changes.filter((change_) => change_.document_path !== DATA.document.path).length;
      const countText =
        `${changes.length} local change${changes.length === 1 ? '' : 's'}` +
        (otherDocumentsCount > 0 ? ` (${otherDocumentsCount} in other documents)` : '');

      const exportButton = createElement(
        'button',
        { type: 'button', class: 'action_button', 'data-testid': 'static-editing-export-action' },
        ['Export changes as JSON'],
      );
      exportButton.addEventListener('click', downloadExport);

      // Discarding needs a second click. A browser dialog would block the
      // page for automated tests.
      const discardButton = createElement(
        'button',
        { type: 'button', class: 'action_button', 'data-testid': 'static-editing-discard-action' },
        ['Discard all'],
      );
      discardButton.addEventListener('click', () => {
        if (discardButton.dataset.confirm === 'true') {
          discardAll();
          return;
        }
        discardButton.dataset.confirm = 'true';
        discardButton.textContent = 'Click again to discard all changes';
      });

      panel.append(
        createElement('sdoc-static-editing-panel-count', { 'data-testid': 'static-editing-change-count' }, [countText]),
        exportButton,
        discardButton,
      );
    });
  }

  //
  // Start.
  //

  store
    .getAll()
    .then((changes) => {
      changes
        .filter((change_) => change_.document_path === DATA.document.path)
        .forEach((change_) => documentChanges.set(change_.key, change_));
    })
    .then(() => {
      // Large documents load their content in chunks. onInsert also covers
      // the nodes of chunks that are inserted later.
      window.StrictDoc.onInsert('[data-static-editing-node]', setUpEditButton);
      return renderPanel();
    });

  // Intentional cross-script contract for end-to-end tests and integrations:
  // read the changes of the project in the export format.
  window.StrictDoc.staticEditing = {
    getExport: () => store.getAll().then(buildExport),
    getChangeCount: () => allChanges.length,
  };
})();
